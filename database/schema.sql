-- MySQL 8.0.16 or later. Run as an administrator on a fresh installation.
CREATE DATABASE IF NOT EXISTS petcare CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE petcare;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 full_name VARCHAR(100) NOT NULL,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_salt CHAR(32) NOT NULL,
 password_hash CHAR(64) NOT NULL,
 password_iterations INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE customers (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL,
 email VARCHAR(120) NOT NULL DEFAULT '', address VARCHAR(255) NOT NULL DEFAULT ''
);
CREATE TABLE pets (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, customer_id BIGINT NOT NULL,
 name VARCHAR(100) NOT NULL, species VARCHAR(50) NOT NULL, breed VARCHAR(100) NOT NULL DEFAULT '', birth_date DATE,
 FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE RESTRICT
);
CREATE TABLE services (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE,
 price DECIMAL(10,2) NOT NULL CHECK(price>=0), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE vets (id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE appointments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, pet_id BIGINT NOT NULL, customer_id BIGINT NOT NULL, service_id BIGINT NOT NULL, vet_id BIGINT NOT NULL,
 slot DATETIME NOT NULL, status ENUM('BOOKED','COMPLETED','CANCELLED') NOT NULL DEFAULT 'BOOKED',
 fee DECIMAL(10,2) NOT NULL CHECK(fee>=0),
 occupied_slot DATETIME GENERATED ALWAYS AS (CASE WHEN status<>'CANCELLED' THEN slot ELSE NULL END) STORED,
 FOREIGN KEY(pet_id) REFERENCES pets(id) ON DELETE RESTRICT,
 FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE RESTRICT,
 FOREIGN KEY(vet_id) REFERENCES vets(id) ON DELETE RESTRICT,
 UNIQUE KEY uq_vet_slot(vet_id,occupied_slot), UNIQUE KEY uq_pet_slot(pet_id,occupied_slot), INDEX idx_slot(slot)
);
CREATE TABLE treatments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, appointment_id BIGINT NOT NULL UNIQUE,
 diagnosis VARCHAR(1000) NOT NULL, medication VARCHAR(1000) NOT NULL DEFAULT '', recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT
);
CREATE TABLE payments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, appointment_id BIGINT NOT NULL,
 amount DECIMAL(10,2) NOT NULL CHECK(amount>0), paid_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(appointment_id) REFERENCES appointments(id) ON DELETE RESTRICT
);
